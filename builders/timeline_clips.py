def tick(comp, t, scrubbing=False):
    P = comp.par
    lg = CL(comp)
    now = time.perf_counter()
    if scrubbing:
        _jump[comp.path] = now
    if _poll.get(comp.path, 0) > now and now - _lastpoll.get(comp.path, 0) > 1.0:
        _lastpoll[comp.path] = now
        bump_media(comp)
    scr = scrubbing or (now - _jump.get(comp.path, -9.0) < 0.4) or comp.path in _drag
    held = comp.op('tl_actions').module._drag.get(comp.path, {}).get('kind') == 'scrub'
    if getattr(P, 'Recording', None) is not None and P.Recording.eval():
        scr = held = False            # phase 3 offline take: always full-res sources
