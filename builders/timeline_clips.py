def make_proxies(comp):
    """Start tools/timeline_media.py --proxies in the background (Popen returns at once; ffmpeg never runs in a
    cook); the media json is polled for 5 min so finished proxies show up by themselves."""
    lg = CL(comp)
    srcs = sorted(set(lg.resolve_path(c['src'], REPO) for c in clips(comp)))
    if not srcs:
        return 'no clips'
    log = REPO + '/output/timeline/media.log'
    os.makedirs(os.path.dirname(log), exist_ok=True)
    with open(log, 'a') as lf:
        p = subprocess.Popen([_python(), '-I', TOOL, '--proxies'] + srcs, stdout=lf, stderr=lf,
                             stdin=subprocess.DEVNULL, start_new_session=True, cwd=REPO)
    _poll[comp.path] = time.perf_counter() + 300.0
    return 'pid %d' % p.pid


def pulse(comp, name):
    if name == 'Maxplayers':
        apply_players(comp)
        _assign.pop(comp.path, None)
    elif name == 'Refreshmedia':
        bump_media(comp)
    elif name == 'Makeproxies':
        return make_proxies(comp)
    return name


