    for k, e in zip('xyzw', ('parent().par.Blendmode.menuIndex', 'parent().par.Premult',
                             'parent().par.Fit.menuIndex', 'parent().par.Maxplayers')):
        getattr(g.par, 'vec2value' + k).expr = e
    co = _get(comp, nullTOP, 'clips_out')
    _wire(g, co)
    sw = _get(comp, switchTOP, 'program_src')
    _wire(comp.op('demo_noise'), sw, 0)
    _wire(co, sw, 1)
    sw.par.index.expr = "1 if parent().par.Program.eval() == 'clips' else 0"
    rt.module.apply_players(comp)

    pe = _get(comp, parameterexecuteDAT, 'clips_pars')
    pe.par.op = comp
    pe.par.pars = 'Maxplayers Refreshmedia Makeproxies'
    pe.par.valuechange = True
    pe.par.onpulse = True
    pe.text = CLIP_PARS_CB
    pe.par.active = True

    # clip strip view (one pixel pass; data recooks only on edits, playhead is a uniform)
