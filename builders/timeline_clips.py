    sd.seq.vec.numBlocks = max(int(sd.seq.vec.numBlocks), 2)
    sd.par.vec0name = 'uS'
    sd.par.vec0valuex.expr = 'parent().par.Seek / max(1e-6, parent().par.Length)'
    sd.par.vec0valuey.expr = "parent().op('tl_clips').module.strip_tracks(parent())"
    sd.par.vec0valuez.expr = "len(parent().op('tl_clips').module.clips(parent()))"
    sd.par.vec0valuew.expr = 'parent().par.Play'
    sd.par.vec1name = 'uL'
    sd.par.vec1valuex.expr = "parent().op('tl_actions').module.play_range(parent())[0] / max(1e-6, parent().par.Length)"
    sd.par.vec1valuey.expr = "parent().op('tl_actions').module.play_range(parent())[1] / max(1e-6, parent().par.Length)"
    sd.par.vec1valuez.expr = 'parent().par.Loop'
    spec = _table(comp, 'cliplabels_spec', [['text', 'x', 'y']], False)
    lb = _get(comp, textTOP, 'cliplabels')
    lb.par.outputresolution = 'custom'
    lb.par.resolutionw, lb.par.resolutionh = VIEW_W, CLIP_H
    lb.par.specdat = spec
    lb.par.text = ''
    lb.par.fontsizex = 12
    lb.par.bgalpha = 0
    lb.par.fontcolorr, lb.par.fontcolorg, lb.par.fontcolorb = 0.92, 0.92, 0.92
    cv = _get(comp, overTOP, 'clipview')
    _wire(lb, cv, 0)
    _wire(sd, cv, 1)
    cvo = _get(comp, nullTOP, 'clipview_out')
    _wire(cv, cvo)
    return comp.path


