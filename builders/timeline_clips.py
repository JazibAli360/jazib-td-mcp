# ONE compute pass (T-46/T-47): up to 4 player inputs, fit, weights, ranks, over/add/screen, premultiply.
COMPOSITE_GLSL = '''// clips_comp: TL_timeline clip composite, ONE compute pass (T-46/T-47 safe). Mirrors
// timeline_clips_logic.composite_pixel + fit_scale (tested offline).
// inputs: player0..2 wired, player3 via the tops par; TD_NUM_2D_INPUTS guards every access (spare players unwired).
layout (local_size_x = 8, local_size_y = 8) in;
uniform vec4 uW;     // weight per player slot 0..3
uniform vec4 uR;     // compositing rank per slot (0 = bottom, -1 = not drawn)
uniform vec4 uMode;  // blend (0 over, 1 add, 2 screen), premultiply inputs, fit (0 fit, 1 fill, 2 stretch), players

vec2 fitUV(vec2 uv, vec2 src, vec2 dst, int fit) {
    if (fit == 2 || src.x <= 0.0 || src.y <= 0.0) return uv;
    float s = (fit == 0) ? min(dst.x / src.x, dst.y / src.y) : max(dst.x / src.x, dst.y / src.y);
    return 0.5 + (uv - 0.5) * (dst / (src * s));
}

vec4 slotColor(int s, vec2 uv, vec2 dst, int fit) {
    vec2 su = uv;
#if TD_NUM_2D_INPUTS > 0
    if (s == 0) { su = fitUV(uv, vec2(textureSize(sTD2DInputs[0], 0)), dst, fit);
        if (any(lessThan(su, vec2(0.0))) || any(greaterThan(su, vec2(1.0)))) return vec4(0.0);
        return textureLod(sTD2DInputs[0], su, 0.0); }
#endif
#if TD_NUM_2D_INPUTS > 1
    if (s == 1) { su = fitUV(uv, vec2(textureSize(sTD2DInputs[1], 0)), dst, fit);
        if (any(lessThan(su, vec2(0.0))) || any(greaterThan(su, vec2(1.0)))) return vec4(0.0);
        return textureLod(sTD2DInputs[1], su, 0.0); }
#endif
#if TD_NUM_2D_INPUTS > 2
    if (s == 2) { su = fitUV(uv, vec2(textureSize(sTD2DInputs[2], 0)), dst, fit);
        if (any(lessThan(su, vec2(0.0))) || any(greaterThan(su, vec2(1.0)))) return vec4(0.0);
        return textureLod(sTD2DInputs[2], su, 0.0); }
#endif
#if TD_NUM_2D_INPUTS > 3
    if (s == 3) { su = fitUV(uv, vec2(textureSize(sTD2DInputs[3], 0)), dst, fit);
        if (any(lessThan(su, vec2(0.0))) || any(greaterThan(su, vec2(1.0)))) return vec4(0.0);
        return textureLod(sTD2DInputs[3], su, 0.0); }
#endif
    return vec4(0.0);
}

void main() {
    ivec2 gid = ivec2(gl_GlobalInvocationID.xy);
    vec2 dst = uTDOutputInfo.res.zw;
    if (gid.x >= int(dst.x) || gid.y >= int(dst.y)) return;
    vec2 uv = (vec2(gid) + 0.5) / dst;
    int mode = int(uMode.x + 0.5);
    bool premult = uMode.y > 0.5;
    int fit = int(uMode.z + 0.5);
    int n = min(int(uMode.w + 0.5), TD_NUM_2D_INPUTS);
    float W[4] = float[4](uW.x, uW.y, uW.z, uW.w);
    float R[4] = float[4](uR.x, uR.y, uR.z, uR.w);
    vec4 acc = vec4(0.0);
    for (int r = 0; r < 4; r++) {
        for (int s = 0; s < 4; s++) {
            if (s >= n || int(R[s] + 0.5) != r || R[s] < -0.5 || W[s] <= 0.0) continue;
            vec4 p = slotColor(s, uv, dst, fit);
            if (premult) p.rgb *= p.a;
            vec4 c = p * W[s];
            if (mode == 1) acc = vec4(acc.rgb + c.rgb, min(1.0, acc.a + c.a));
            else if (mode == 2) acc = vec4(1.0 - (1.0 - acc.rgb) * (1.0 - c.rgb), c.a + acc.a * (1.0 - c.a));
            else acc = c + acc * (1.0 - c.a);
        }
    }
    TDImageStoreOutput(0, ivec3(gid, 0), TDOutputSwizzle(acc));
}
'''

STRIP_GLSL = '''// clipstrip_draw: clip strip (tracks, clip bars, trim handles, selection, loop region, playhead). ONE pixel pass.
// input 0 = clipview_tex: n x 4 mono float rows (u0, u1, track(+.5 disabled), flag) per clip, bottom-first.
uniform vec4 uS;   // playhead u, tracks, clips, play
uniform vec4 uL;   // loop in u, loop out u, loop on, unused
out vec4 fragColor;
float rowv(int row, int x) { return texelFetch(sTD2DInputs[0], ivec2(x, row), 0).r; }
void main() {
    vec2 res = uTDOutputInfo.res.zw;
    vec2 uv = vUV.st;
    vec2 px = uv * res;
    int nt = max(int(uS.y + 0.5), 1);
    float band = 1.0 / float(nt);
    int tr = min(int(uv.y / band), nt - 1);
    vec3 col = (tr % 2 == 1) ? vec3(0.085) : vec3(0.065);
    if (uL.z > 0.5 && uv.x >= uL.x && uv.x <= uL.y) col += vec3(0.012, 0.02, 0.035);
    if (abs(fract(uv.y / band + 0.5) - 0.5) * band * res.y < 0.6) col = vec3(0.2);
    ivec2 ts = textureSize(sTD2DInputs[0], 0);
    int nc = min(int(uS.z + 0.5), ts.x);
    for (int i = 0; i < 512; i++) {
        if (i >= nc || ts.y < 4) break;
        float u0 = rowv(0, i);
        if (u0 < -0.5) break;
        float u1 = rowv(1, i);
        float trf = rowv(2, i);
        float fl = rowv(3, i);
        int t = int(trf);
        bool dis = fract(trf) > 0.25;
        float b = float(t) * band;
        float pad = band * 0.12;
        float v0 = b + pad;
        float v1 = b + band - pad;
        if (uv.y < v0 || uv.y > v1 || uv.x < u0 || uv.x > u1) continue;
        bool vis = uS.x >= u0 && uS.x < u1;
        vec3 c = vis ? vec3(0.28, 0.52, 0.82) : vec3(0.20, 0.32, 0.48);
        if (dis) c = vec3(0.16);
        float ex = min(px.x - u0 * res.x, u1 * res.x - px.x);
        float ey = min(px.y - v0 * res.y, v1 * res.y - px.y);
        if (ex < 6.0) c *= 1.3;
        if (min(ex, ey) < 1.2) c = fl > 0.5 ? vec3(1.0, 0.85, 0.4) : vec3(0.7);
        col = c;
    }
    float dp = abs(px.x - uS.x * res.x);
    col = mix(col, uS.w > 0.5 ? vec3(1.0, 0.25, 0.2) : vec3(0.95), 1.0 - smoothstep(0.25, 1.75, dp));
    fragColor = TDOutputSwizzle(vec4(col, 1.0));
}
'''

