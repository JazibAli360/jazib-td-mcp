def _rec_pars(comp):
    def page(name):
        for p in comp.customPages:
            if p.name == name:
                return p
        return comp.appendCustomPage(name)

    def add(pg, kind, name, label, menu=None, **kw):
        p = getattr(comp.par, name, None)
        new = p is None
        if new:
            p = getattr(pg, 'append' + kind)(name, label=label)[0]
        p.label = label
        if menu:
            p.menuNames, p.menuLabels = menu
        for k, v in kw.items():
            if k != 'default':
                setattr(p, k, v)
        if 'default' in kw:
            p.default = kw['default']
            if new:
                p.val = kw['default']
        return p

    rc = page('Record')
    add(rc, 'Float', 'Recin', 'Record in (s)', default=0.0, normMin=0, normMax=16, min=0, clampMin=True)
    add(rc, 'Float', 'Recout', 'Record out (s; <= in = loop range)', default=5.0, normMin=0, normMax=16, min=0,
        clampMin=True)
    add(rc, 'Float', 'Recfps', 'File frame rate', default=60.0, normMin=1, normMax=120, min=1, clampMin=True)
    add(rc, 'Menu', 'Reccodec', 'Codec', default='prores4444',
        menu=(['prores4444', 'prores422hq'], ['ProRes 4444 (alpha)', 'ProRes 422 HQ']))
    add(rc, 'Str', 'Recfile', 'File (.mov; empty = output/timeline/renders/TL_<time>.mov)', default='')
    add(rc, 'Pulse', 'Record', 'Record (offline, frame-accurate)')
    add(rc, 'Pulse', 'Recabort', 'Abort take')
    p = add(rc, 'Toggle', 'Recording', 'Recording', default=False)
    p.readOnly = True
    p = add(rc, 'Str', 'Recstatus', 'Status', default='')
    p.readOnly = True
    add(rc, 'Menu', 'Exportformat', 'Marker export format', default='csv',
        menu=(['csv', 'json', 'ae'], ['CSV (time, frame, name)', 'JSON', 'After Effects markers JSON']))
    add(rc, 'Pulse', 'Exportmarkers', 'Export markers')
    add(rc, 'Pulse', 'Exportlanes', 'Export lanes (per-frame CSV, record range)')
    p = add(rc, 'Str', 'Lastexport', 'Last export', default='')
    p.readOnly = True

    au = page('Audio')
    add(au, 'File', 'Audiofile', 'Master audio file (empty = none)', default='')
    add(au, 'Float', 'Audiooffset', 'Master starts at (s)', default=0.0, normMin=0, normMax=16)
    add(au, 'Float', 'Audiogain', 'Master gain', default=1.0, normMin=0, normMax=2, min=0, clampMin=True)
    add(au, 'Toggle', 'Clipaudio', 'Clip audio', default=True)
    add(au, 'Float', 'Clipgain', 'Clip audio gain', default=1.0, normMin=0, normMax=2, min=0, clampMin=True)
    add(au, 'Toggle', 'Listen', 'Listen (Mac default output, only while playing)', default=False)
    add(au, 'Float', 'Outvolume', 'Output volume', default=0.8, normMin=0, normMax=1, min=0, clampMin=True)


def build_record(comp):
    _rec_pars(comp)
    lgd = _get(comp, textDAT, 'tl_record_logic')
    lgd.text = open(TL_ROOT + '/timeline_record_logic.py').read()
    rt = _get(comp, textDAT, 'tl_record')
    rt.text = REC_RT.replace('@REPO@', TL_ROOT.rsplit('/', 1)[0])
    rp = _get(comp, parameterexecuteDAT, 'record_pars')
    rp.par.op = comp
    rp.par.pars = 'Record Recabort Exportmarkers Exportlanes'
    rp.par.onpulse = True
    rp.par.valuechange = False
    rp.text = REC_PARS_CB
    rp.par.active = True
    pm = _get(comp, executeDAT, 'rec_pump')
    pm.text = PUMP
    for p in ('start', 'create', 'exit', 'framestart', 'playstatechange', 'devicechange', 'projectpresave',
              'projectpostsave'):
        setattr(pm.par, p, False)
    pm.par.frameend = True
    pm.par.active = False      # T-97: toggle after a text rewrite so frame callbacks fire
    pm.par.active = True

    # audio
    am = _get(comp, audiofileinCHOP, 'audio_master')
    am.par.file.expr = ("(lambda p: p if (not p or p.startswith('/')) else '%s/' + p)(parent().par.Audiofile.eval())"
                        % TL_ROOT.rsplit('/', 1)[0])
    am.par.playmode = 'specify'
    am.par.indexunit = 'seconds'
    am.par.index.expr = 'max(0.0, parent().par.Seek - parent().par.Audiooffset)'
    am.par.volume.expr = ('parent().par.Audiogain if (parent().par.Audiofile.eval() and parent().par.Seek >= '
                          'parent().par.Audiooffset) else 0.0')
    am.par.repeat = 'off'
    clips = []
    for i in range(4):
        a = _get(comp, audiofileinCHOP, 'aclip%d' % i)
        if a.par.file.eval().startswith('$TT') or 'JeremyCaulfield' in a.par.file.eval():
            a.par.file = ''
        a.par.playmode = 'specify'
        a.par.indexunit = 'seconds'
        a.par.repeat = 'off'
        a.par.volume = 0
        a.par.play = False
        clips.append(a)
    mx = _get(comp, mathCHOP, 'audio_mix')
    mx.par.chopop = 'add'
    mx.par.match = 'index'
    _wire(am, mx, 0)
    for i, a in enumerate(clips):
        _wire(a, mx, i + 1)
    nu = _get(comp, nullCHOP, 'audio_null')
    _wire(mx, nu)
    ao = _get(comp, outCHOP, 'audio_out')
    _wire(nu, ao)
    dv = _get(comp, audiodeviceoutCHOP, 'audio_device')
    _wire(nu, dv)
    dv.par.active.expr = 'bool(parent().par.Listen and parent().par.Play and not parent().par.Recording)'
    if hasattr(dv.par, 'volume'):
        dv.par.volume.expr = 'parent().par.Outvolume'
    return comp
