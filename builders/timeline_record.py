"""TL_timeline phase 3 builder part: offline recording, audio track, marker / lane export.

Not run on its own: builders/timeline.py build(..., record=True) execs this file with its own globals (_get, _wire,
_table, _sd, TL_ROOT) and calls build_record(comp). Pure logic: builders/timeline_record_logic.py (copied into
`tl_record_logic`, tests test/test_timeline_record.py); outside TD: tools/timeline_render.py (mix + mux + sync check).
Plan + live results: docs/builds/timeline_phase3.md. Rules kept: never change project.cookRate (T-64), a fresh Movie
File Out per take (T-30) removed through safe_destroy, realTime off only for the take and restored by the pump itself,
no pixel readback (T-74), plain data in storage (T-67), ffmpeg runs with Popen outside the cook. Pure ASCII.
"""

REC_RT = r'''# tl_record: TD side of TL_timeline phase 3 (offline take, audio track, exports). Generated by
# builders/timeline_record.py. Pure maths: tl_record_logic. State in storage 'tl_rec' (plain dict, T-67).
import os, json, time, subprocess
REPO = '@REPO@'
OUT = REPO + '/output/timeline'
TOOL = REPO + '/tools/timeline_render.py'
PRIME = 10          # TD frames the playhead is held at the in point before Record goes on (players load)
SETTLE = 15         # TD frames after Record goes off before the movie is closed and handed to ffmpeg


def RL(comp):
    return comp.op('tl_record_logic').module


def H():
    h = op('/jazib_mcp/handlers')                  # the MCP; None in a project without it (drop-in, 28 Oct)
    return h.module if h is not None else None


def rec(comp):
    r = comp.fetch('tl_rec', None)
    return dict(r) if r else {}


def put(comp, r):
    comp.store('tl_rec', dict(r))
    st = r.get('state', '')
    on = st in ('setup', 'arm', 'run')
    if bool(comp.par.Recording.eval()) != on:
        comp.par.Recording = on
    msg = r.get('msg', st)
    if comp.par.Recstatus.eval() != msg:
        comp.par.Recstatus = msg


def active(comp):
    return rec(comp).get('state') in ('arm', 'run')


def _python():
    for p in ('/usr/bin/python3', '/opt/homebrew/bin/python3', '/usr/local/bin/python3'):
        if os.path.isfile(p):
            return p
    return 'python3'


def _stamp():
    return time.strftime('%Y%m%d_%H%M%S')


def _abs(p, default):
    p = (p or '').strip()
    if not p:
        return default
    if not os.path.isabs(p):
        p = os.path.join(REPO, p)
    return p


# ---------------------------------------------------------------- record
def start(comp):
    """Record pulse: plan the take, make a fresh Movie File Out, then the pump runs the rest frame by frame."""
    r = rec(comp)
    if r.get('state') in ('setup', 'arm', 'run', 'final', 'mux'):
        return 'busy: ' + r.get('state')
    P = comp.par
    a, b = float(P.Recin), float(P.Recout)
    if b <= a:
        a, b = float(P.Inpoint), float(P.Outpoint)
    fps = float(P.Recfps) or float(P.Fps)
    rate = float(project.cookRate)            # read only: never changed live (T-64)
    plan = RL(comp).record_plan(a, b, fps, rate)
    out = _abs(P.Recfile.eval(), OUT + '/renders/TL_%s.mov' % _stamp())
    if not out.lower().endswith('.mov'):
        out += '.mov'
    os.makedirs(os.path.dirname(out), exist_ok=True)
    video = out[:-4] + '_video.mov'
    for f in (out, video, out + '.report.json'):
        if os.path.isfile(f):
            os.remove(f)
    hd = H()
    if hd is None:
        raise RuntimeError('Record needs the Jazib TD MCP (/jazib_mcp: codec table + ffmpeg mux) in this project')
    spec = hd.RENDER_CODECS[P.Reccodec.eval()]
    i = 1
    while comp.op('rec_take%d' % i) is not None:
        i += 1
    m = comp.create(moviefileoutTOP, 'rec_take%d' % i)
    m.viewer = False
    src = comp.op('program_out')
    m.inputConnectors[0].connect(src.inputs[0] if src.inputs else src)
    m.nodeX, m.nodeY = src.nodeX, src.nodeY - 160
    for k, v in (('type', 'movie'), ('moviecontainer', 'mov'), ('videocodec', spec[0]), ('file', video), ('fps', fps)):
        getattr(m.par, k).val = v
    put(comp, {'state': 'setup', 'wait': 2, 'plan': plan, 'out': out, 'video': video, 'mfo': m.path,
               'codec': P.Reccodec.eval(), 'k': 0, 'n': 0, 'msg': 'setting up %d frames' % plan['frames'],
               'prev': {'play': bool(P.Play), 'seek': float(P.Seek), 'rt': bool(project.realTime)}})
    return 'started'


def abort(comp, why='aborted'):
    r = rec(comp)
    m = op(r.get('mfo', '')) if r.get('mfo') else None
    if m is not None:
        m.par.record = False
    _restore(comp, r)
    r.update({'state': 'final', 'wait': SETTLE, 'msg': why, 'aborted': True})
    put(comp, r)


def _restore(comp, r):
    pv = r.get('prev') or {}
    project.realTime = bool(pv.get('rt', True))
    comp.par.Play = False
    if 'seek' in pv:
        comp.par.Seek = pv['seek']


def clock(comp):
    """Called by tl_actions.tick at frame start. Returns the take's timeline time, or None when not recording."""
    r = rec(comp)
    st = r.get('state')
    if st not in ('arm', 'run'):
        return None
    pl = r['plan']
    if st == 'arm':
        r['prime'] = int(r.get('prime', PRIME)) - 1
        if r['prime'] <= 0:
            r['state'] = 'run'          # this frame (t = in) is the take's frame 0; the pump records it at frame end
            r['k'] = 0
        put(comp, r)
        return pl['in']
    r['k'] = int(r['k']) + 1
    put(comp, r)
    return RL(comp).take_time(pl, r['k'])


def pump(comp):
    """rec_pump Execute DAT, frame end: codec setup, force-cook the Movie File Out per frame, finish, mux."""
    r = rec(comp)
    st = r.get('state')
    if not st or st == 'done':
        return
    m = op(r.get('mfo', '')) if r.get('mfo') else None
    if st == 'setup':
        r['wait'] = int(r['wait']) - 1
        if r['wait'] > 0:
            put(comp, r)
            return
        try:
            hd = H()
            if hd is None:
                raise RuntimeError('Record needs the Jazib TD MCP (/jazib_mcp) in this project')
            spec = hd.RENDER_CODECS[r['codec']]
            ct = m.par.videocodectype
            pick = hd.pick_menu_entry(ct.menuNames, ct.menuLabels, all_of=spec[1].get('all', ()),
                                      none_of=spec[1].get('none', ()))
            if pick is None:
                raise RuntimeError('no codec type for %s' % r['codec'])
            ct.val = pick
            if spec[2]:
                pf = m.par.videopixelformat
                pp = hd.pick_menu_entry(pf.menuNames, pf.menuLabels, any_of=spec[2]['any'])
                if pp is not None:
                    pf.val = pp
        except Exception as e:  # noqa: BLE001
            r.update({'state': 'final', 'wait': 1, 'msg': 'error: %s' % str(e)[:120], 'aborted': True})
            put(comp, r)
            return
        comp.par.Play = False
        r['prev']['rt'] = bool(project.realTime)
        project.realTime = False                  # offline: no dropped frames (T-11); restored below
        r.update({'state': 'arm', 'prime': PRIME, 'msg': 'priming', 't0': time.time()})
        put(comp, r)
        return
    if st == 'run':
        if m is None:
            abort(comp, 'error: recorder gone')
            return
        if not m.par.record.eval():
            m.par.record = True
        m.cook(force=True)
        r['n'] = int(r['n']) + 1
        pl = r['plan']
        r['msg'] = 'recording %d / %d' % (r['n'], pl['cooks'])
        if r['n'] >= pl['cooks']:
            m.par.record = False
            _restore(comp, r)
            r.update({'state': 'final', 'wait': SETTLE, 'secs': round(time.time() - r.get('t0', time.time()), 3),
                      'msg': 'closing movie'})
        put(comp, r)
        return
    if st == 'final':
        r['wait'] = int(r['wait']) - 1
        if r['wait'] > 0:
            put(comp, r)
            return
        if m is not None:
            _sd(m)
        if r.get('aborted'):
            r['state'] = 'done'
            put(comp, r)
            return
        try:
            planf = r['out'][:-4] + '.plan.json'
            doc = dict(r['plan'])
            doc.update({'video': r['video'], 'out': r['out'], 'segments': segments(comp, r['plan'])})
            with open(planf, 'w') as f:
                json.dump(doc, f, indent=1)
            log = open(r['out'][:-4] + '.mux.log', 'w')
            subprocess.Popen([_python(), '-I', TOOL, 'mux', planf], stdout=log, stderr=subprocess.STDOUT,
                             close_fds=True)
            r.update({'state': 'mux', 'msg': 'muxing audio', 'poll': 0})
        except Exception as e:  # noqa: BLE001
            r.update({'state': 'done', 'msg': 'error: %s' % str(e)[:120]})
        put(comp, r)
        return
    if st == 'mux':
        r['poll'] = int(r.get('poll', 0)) + 1
        if r['poll'] % 30:
            comp.store('tl_rec', r)
            return
        rp = r['out'] + '.report.json'
        if os.path.isfile(rp):
            try:
                d = json.load(open(rp))
                r['report'] = {k: d.get(k) for k in ('ok', 'frames_counted', 'frames_expected', 'error')}
                r['msg'] = '%s %s frames -> %s' % ('ok' if d.get('ok') else 'CHECK', d.get('frames_counted'),
                                                   os.path.basename(r['out']))
            except Exception as e:  # noqa: BLE001
                r['msg'] = 'report unreadable: %s' % str(e)[:80]
            r['state'] = 'done'
        elif r['poll'] > 60 * 120:
            r.update({'state': 'done', 'msg': 'mux timed out (see .mux.log)'})
        put(comp, r)


def _sd(o):
    h = op('/jazib_mcp/handlers')                  # drop-in: no MCP in this project -> plain destroy
    f = globals().get('safe_destroy') or (getattr(h.module, 'safe_destroy', None) if h is not None else None) or \
        (lambda o: o.destroy())
    return f(o)


# ---------------------------------------------------------------- audio
def has_audio(comp, src):
    m = comp.op('tl_clips').module.media(comp).get(src, {})
    return bool(m.get('audio'))


def segments(comp, plan):
    """Offline mix pieces for the take (clips with audio + the master file)."""
    P = comp.par
    ck = comp.op('tl_clips').module
    cl = ck.clips(comp) if bool(P.Clipaudio) else []
    lg = comp.op('tl_clips_logic').module
    root = ck.REPO
    rcl = [dict(c, src=lg.resolve_path(c['src'], root)) for c in cl]
    master = _abs(P.Audiofile.eval(), '')
    master = master if master and os.path.isfile(master) else None
    segs, skipped = RL(comp).audio_segments(rcl, lambda s: has_audio(comp, s), plan['in'], plan['out'], master,
                                            float(P.Audiooffset), float(P.Audiogain), float(P.Clipgain))
    return segs


def audio_tick(comp, t):
    """Frame start, after the clips tick: clip audio players follow the clip players' slots; index = source time,
    volume = clip weight x Clipgain. The master follows Seek by expression. Device out: expression (Play + Listen)."""
    P = comp.par
    ck = comp.op('tl_clips')
    want = {}
    if ck is not None and bool(P.Clipaudio):
        m = ck.module
        lg = comp.op('tl_clips_logic').module
        assign = m._assign.get(comp.path, {})
        by_id = dict((c['id'], c) for c in m.clips(comp))
        for c, w in lg.active_clips(list(by_id.values()), t):
            s = assign.get(c['id'])
            src = lg.resolve_path(c['src'], m.REPO)
            if s is None or not has_audio(comp, src):
                continue
            want[s] = (src, max(0.0, lg.source_time(c, t)), w * float(P.Clipgain))
    am = comp.op('audio_master')
    if am is not None and am.bypass != (not am.par.file.eval()):
        am.bypass = not am.par.file.eval()        # no file = no 'No filename' warning, no samples
    for i in range(4):
        a = comp.op('aclip%d' % i)
        if a is None:
            continue
        if a.bypass != (i not in want):
            a.bypass = i not in want
        if i in want:
            src, idx, vol = want[i]
            if a.par.file.eval() != src:
                a.par.file = src
            a.par.index = idx
            if a.par.volume.eval() != vol:
                a.par.volume = vol
            if not a.par.play.eval():
                a.par.play = True
        else:
            if a.par.volume.eval() != 0:
                a.par.volume = 0
            if a.par.play.eval():
                a.par.play = False


# ---------------------------------------------------------------- exports
def export(comp, what):
    P = comp.par
    fmt = P.Exportformat.eval()
    A = comp.op('tl_actions').module
    d = OUT + '/export'
    os.makedirs(d, exist_ok=True)
    if what == 'markers':
        ext = 'csv' if fmt == 'csv' else 'json'
        path = '%s/markers_%s%s.%s' % (d, _stamp(), '_ae' if fmt == 'ae' else '', ext)
        txt = RL(comp).markers_text(A.markers(comp), fmt, float(P.Fps), comp.path)
    else:
        a, b = float(P.Recin), float(P.Recout)
        if b <= a:
            a, b = float(P.Inpoint), float(P.Outpoint)
        lg = comp.op('tl_logic').module
        names = [ln['name'] for ln in A.lanes(comp)]
        path = '%s/lanes_%s.csv' % (d, _stamp())
        txt = RL(comp).lanes_csv(names, lambda n, t: lg.lane_value(A.lane_keys(comp, n), t), a, b,
                                 float(P.Recfps) or float(P.Fps))
    with open(path, 'w') as f:
        f.write(txt)
    P.Lastexport = path
    return path


def pulse(comp, name):
    if name == 'Record':
        P = comp.par
        P.Recstatus = start(comp)
    elif name == 'Recabort':
        if rec(comp).get('state') in ('setup', 'arm', 'run'):
            abort(comp)
    elif name == 'Exportmarkers':
        export(comp, 'markers')
    elif name == 'Exportlanes':
        export(comp, 'lanes')
'''

