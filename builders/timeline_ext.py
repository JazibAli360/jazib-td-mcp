"""TL_timeline phase 4 builder part: the agent-ready API (Python extension TimelineExt + tl_api_logic).

Not run on its own: builders/timeline.py build(..., api=True) (the default) execs this file with its own globals
(_get, TL_ROOT) and calls build_api(comp). Pure logic: builders/timeline_api_logic.py (copied into `tl_api_logic`,
tests test/test_timeline_api.py). MCP tools td_timeline_* (src/timeline.js) call the same methods through the
handlers commands timeline_* (docs/PROTOCOL.md "Timeline API"). Plan + live checks: docs/builds/timeline_phase4.md.
The extension is stateless (all state is in the COMP's tables, pars and storage), so the handlers may also make a
fresh TimelineExt(comp) from the DAT module when TD has not (re)initialised the extension. Pure ASCII.
"""

EXT_TEXT = r'''# TimelineExt: agent-ready API of TL_timeline (phase 4). Generated by builders/timeline_ext.py.
# Edit a show by DATA: every edit goes through tl_api_logic.apply_ops (validated, atomic by default) and writes back
# only the tables / pars that changed. Stateless: state lives in the COMP's tables, pars and storage.
# In TD:  op('TL_timeline').AddKey('level', '8b', 0.9)   op('TL_timeline').Edit([{'op': 'add_marker', 't': 8, 'name': 'Drop'}])
import json
import os
from td import tableDAT


class TimelineExt(object):
    """Promoted methods (capitalised) are the API. Every edit returns {ok, results, changed, removed, settings,
    summary}; reads return plain JSON-able dicts."""

    def __init__(self, ownerComp):
        self.ownerComp = ownerComp

    # ------------------------------------------------------------ internals
    def _api(self):
        c = self.ownerComp
        a = c.op('tl_api_logic').module
        cl = c.op('tl_clips_logic')
        a.bind(c.op('tl_logic').module, cl.module if (cl is not None and c.op('clips') is not None) else None)
        return a

    def _A(self):
        return self.ownerComp.op('tl_actions').module

    def _rows(self, name):
        d = self.ownerComp.op(name)
        if d is None:
            return None
        return [[cell.val for cell in r] for r in d.rows()]

    def _settings(self, api):
        out = {}
        for k, spec in api.SETTINGS.items():
            p = getattr(self.ownerComp.par, spec[0], None)
            if p is None:
                continue
            v = p.eval()
            kind = spec[1]
            if kind == 'bool':
                v = bool(v)
            elif kind == 'int':
                v = int(v)
            elif kind == 'float':
                v = float(v)
            else:
                v = str(v)
            out[k] = v
        return out

    def _show(self, api):
        lanes = self._rows('lanes') or [['name', 'op', 'par', 'min', 'max', 'enabled']]
        keys = {}
        for ln in self.ownerComp.op('tl_logic').module.parse_lanes(lanes):
            keys[ln['name']] = self._rows('lane_' + ln['name']) or []
        return api.show_from_tables(self._settings(api), lanes, keys, self._rows('markers') or [['time', 'name']],
                                    self._rows('clips'))

    def _destroy(self, o):
        h = op('/jazib_mcp/handlers')
        f = getattr(h.module, 'safe_destroy', None) if h is not None else None
        if f is not None:
            return f(o)
        o.destroy()

    def _restage(self, added, removed):
        """Keep the stored stage plan (jz_stages) in step with lane tables, then re-apply it (readable network)."""
        c = self.ownerComp
        plan = c.fetch('jz_stages', None)
        if not isinstance(plan, list) or not (added or removed):
            return
        for s in plan:
            ops_ = s.get('ops', []) if isinstance(s, dict) else []
            if 'lanes' in ops_:
                s['ops'] = [n for n in ops_ if n not in removed] + [n for n in added if n not in ops_]
        c.store('jz_stages', plan)
        h = op('/jazib_mcp/handlers')
        try:
            if h is not None and hasattr(h.module, 'restage'):
                h.module.restage(c)
        except Exception:  # noqa: BLE001  layout never fails an edit
            pass

    def _write(self, api, before, after):
        c = self.ownerComp
        changed, removed = api.changed_tables(before, after)
        sets = api.changed_settings(before, after)
        warnings, added = [], []
        for name, rows in sorted(changed.items()):
            d = c.op(name)
            if d is None:
                d = c.create(tableDAT, name)
                d.viewer = True
                added.append(name)
            d.clear()
            for r in rows:
                d.appendRow(r)
        for name in removed:
            d = c.op(name)
            if d is not None:
                self._destroy(d)
        order = ['length'] + [k for k in sets if k != 'length']   # Length first: In/Out/Seek ranges follow it
        for k in order:
            if k not in sets:
                continue
            p = getattr(c.par, api.SETTINGS[k][0], None)
            if p is None:
                warnings.append('setting %s: no par %s on this COMP (phase 2 not built?)' % (k, api.SETTINGS[k][0]))
                continue
            p.val = sets[k]
        self._restage(added, removed)
        return sorted(changed), removed, sets, warnings

    def _edit_reply(self, api, before, after, results, ok, dry, atomic=True):
        if dry or (atomic and not ok):
            changed, removed = api.changed_tables(before, after)
            r = {'ok': ok, 'dry': bool(dry), 'written': False, 'changed': sorted(changed), 'removed': removed,
                 'settings': api.changed_settings(before, after), 'results': results}
        else:
            changed, removed, sets, warns = self._write(api, before, after)
            r = {'ok': ok, 'dry': False, 'written': True, 'changed': changed, 'removed': removed, 'settings': sets,
                 'results': results}
            if warns:
                r['warnings'] = warns
        r['applied'] = sum(1 for x in results if x.get('ok'))
        r['summary'] = api.summary(after)
        return r

    # ------------------------------------------------------------ reads
    def Show(self, parts=None):
        """The show as data (tl-show v1): settings, lanes (+ keys), markers, clips. parts = subset of
        settings / lanes / markers / clips."""
        api = self._api()
        sh = self._show(api)
        if parts:
            bad = [p for p in parts if p not in api.PARTS]
            if bad:
                raise ValueError('parts must be among %s, got %s' % (list(api.PARTS), bad))
            sh = dict((k, v) for k, v in sh.items() if k in ('format', 'v') or k in parts)
        return sh

    def State(self, at=None):
        """Transport + what is playing now; at = list of times -> lane values there (pure maths, no seek)."""
        c = self.ownerComp
        P = c.par
        api = self._api()
        sh = self._show(api)
        st = self._A().state(c)
        t = float(P.Seek)
        r = {'comp': c.path, 't': t, 'frame': int(st.get('frame', 0)), 'play': bool(P.Play), 'rate': float(P.Rate),
             'loop': bool(P.Loop), 'inpoint': float(P.Inpoint), 'outpoint': float(P.Outpoint),
             'length': float(P.Length), 'fps': float(P.Fps), 'bpm': float(P.Bpm), 'clockmode': P.Clockmode.eval(),
             'timecode': P.Timecode.eval(), 'barbeat': P.Barbeat.eval(), 'marker': P.Marker.eval(),
             'wraps': int(st.get('wraps', 0)), 'values': api.lane_values(sh, t), 'summary': api.summary(sh)}
        ls = self._rows('lane_status')
        if ls and len(ls) > 1:
            r['lane_status'] = [dict(zip(ls[0], row)) for row in ls[1:]]
        if getattr(P, 'Clipactive', None) is not None:
            r['clips_active'] = P.Clipactive.eval().split()
            err = c.fetch('tl_clips_err', '')
            if err:
                r['clips_error'] = err
        rec = c.fetch('tl_rec', None)
        if isinstance(rec, dict):
            r['recording'] = dict((k, v) for k, v in rec.items() if k != 'saved')
        if at:
            ctx = api.Ctx.of(sh)
            r['at'] = [{'t': api.to_seconds(x, ctx), 'values': api.lane_values(sh, api.to_seconds(x, ctx))}
                       for x in list(at)[:64]]
        return r

    def Sample(self, t):
        api = self._api()
        sh = self._show(api)
        return api.lane_values(sh, api.to_seconds(t, api.Ctx.of(sh)))

    # ------------------------------------------------------------ edits (all through Edit)
    def Edit(self, ops, atomic=True, dry=False):
        """ops = [{'op': 'add_key', ...}, ...] (tl_api_logic.OPS). atomic: one bad op = nothing written."""
        api = self._api()
        before = self._show(api)
        after, results, ok = api.apply_ops(before, ops, atomic)
        return self._edit_reply(api, before, after, results, ok, dry, atomic)

    def _one(self, _kind, **kw):
        d = dict((k, v) for k, v in kw.items() if v is not None)
        d['op'] = _kind
        return self.Edit([d])

    def AddKey(self, lane, t, v, interp='linear', snap=False):
        return self._one('add_key', lane=lane, t=t, v=v, interp=interp, snap=snap)

    def MoveKey(self, lane, at=None, index=None, t=None, v=None, interp=None, by=None, snap=False):
        return self._one('move_key', lane=lane, at=at, index=index, t=t, v=v, interp=interp, by=by, snap=snap)

    def DeleteKey(self, lane, at=None, index=None):
        return self._one('delete_key', lane=lane, at=at, index=index)

    def SetKeys(self, lane, keys):
        return self._one('set_keys', lane=lane, keys=keys)

    def AddLane(self, name, target=None, op=None, par=None, min=0.0, max=1.0, enabled=True, keys=None):
        return self._one('add_lane', name=name, target=target, op=op, par=par, min=min, max=max, enabled=enabled,
                         keys=keys or [])

    def SetLane(self, name, **kw):
        return self._one('set_lane', name=name, **kw)

    def BindLane(self, name, target):
        return self._one('set_lane', name=name, target=target)

    def DeleteLane(self, name):
        return self._one('delete_lane', name=name)

    def AddMarker(self, t, name, snap=False):
        return self._one('add_marker', t=t, name=name, snap=snap)

    def MoveMarker(self, name=None, at=None, t=None, by=None, rename=None):
        return self._one('move_marker', name=name, at=at, t=t, by=by, rename=rename)

    def DeleteMarker(self, name=None, at=None):
        return self._one('delete_marker', name=name, at=at)

    def AddClip(self, **kw):
        return self._one('add_clip', **kw)

    def SetClip(self, id, **kw):
        return self._one('set_clip', id=id, **kw)

    def MoveClip(self, id, start=None, track=None, by=None, snap=False):
        return self._one('move_clip', id=id, start=start, track=track, by=by, snap=snap)

    def TrimClip(self, id, edge, t, snap=False):
        """Like the strip drag: the out edge stops at the source end (media json, when the clip runtime has it)."""
        src_dur = None
        rt = self.ownerComp.op('tl_clips')
        if rt is not None:
            try:
                m = rt.module
                cl = [x for x in m.clips(self.ownerComp) if x['id'] == id]
                if cl:
                    lg = m.CL(self.ownerComp)
                    info = m.media(self.ownerComp).get(lg.resolve_path(cl[0]['src'], m.REPO), {})
                    src_dur = float(info.get('dur', 0) or 0) or None
            except Exception:  # noqa: BLE001  no media info = no limit
                src_dur = None
        return self._one('trim_clip', id=id, edge=edge, t=t, snap=snap, src_dur=src_dur)

    def DeleteClip(self, id):
        return self._one('delete_clip', id=id)

    def Set(self, **settings):
        return self.Edit([dict(settings, op='set')])

    def Load(self, show, mode='replace', dry=False):
        """A whole show (dict or JSON text). replace: the parts present in it replace the COMP's (missing parts
        stay); merge: same-named lanes / clips / markers replaced, new ones added, the rest kept."""
        api = self._api()
        if isinstance(show, str):
            show = json.loads(show)
        before = self._show(api)
        if mode not in ('replace', 'merge'):
            raise ValueError("mode must be 'replace' or 'merge'")
        try:
            after = api.norm_show(show, before) if mode == 'replace' else api.merge_show(before, show)
        except api.OpError as e:
            return {'ok': False, 'written': False, 'error': str(e), 'results': []}
        return self._edit_reply(api, before, after, [{'op': 'load', 'mode': mode, 'ok': True}], True, dry)

    # ------------------------------------------------------------ transport
    def Transport(self, action=None, **kw):
        """action: play pause toggle stop seek step start end next_marker prev_marker next_key prev_key;
        kw: t / frame (seek), n (step), rate, loop, inpoint, outpoint (any time form). Returns State()."""
        c = self.ownerComp
        P = c.par
        api = self._api()
        sh = self._show(api)
        ctx = api.Ctx.of(sh)
        ktimes = []
        if action in ('next_key', 'prev_key'):
            lns = sh['lanes']
            if kw.get('lane') is not None:
                lns = [l for l in lns if l['name'] == kw['lane']]
            elif lns:
                lns = [lns[min(max(int(P.Lane), 0), len(lns) - 1)]]
            ktimes = [k[0] for l in lns for k in l['keys']]
        cur = {'seek': float(P.Seek), 'play': bool(P.Play), 'inpoint': float(P.Inpoint),
               'outpoint': float(P.Outpoint), 'length': float(P.Length)}
        plan = api.transport_plan(action, kw, cur, ctx, ktimes)
        for name in ('Rate', 'Loop', 'Inpoint', 'Outpoint', 'Seek', 'Play'):
            if name in plan:
                getattr(P, name).val = plan[name]
        r = self.State()
        r['set'] = plan
        return r

    def Play(self):
        return self.Transport('play')

    def Pause(self):
        return self.Transport('pause')

    def Stop(self):
        return self.Transport('stop')

    def Seek(self, t=None, frame=None):
        return self.Transport('seek', t=t, frame=frame)

    def Step(self, n=1):
        return self.Transport('step', n=n)

    # ------------------------------------------------------------ export
    def Export(self, what='show', file=None, start=None, end=None, fps=None, lanes=None):
        """what: show (tl-show JSON) | lanes_csv (per-frame values start..end at fps) | markers_json | markers_csv.
        file: absolute path (the MCP keeps it under output/timeline/); without it the text comes back inline."""
        api = self._api()
        sh = self._show(api)
        ctx = api.Ctx.of(sh)
        r = {'what': what}
        if what == 'show':
            text = json.dumps(sh, indent=1, sort_keys=True)
        elif what == 'lanes_csv':
            a = api.to_seconds(start, ctx) if start is not None else 0.0
            b = api.to_seconds(end, ctx) if end is not None else float(sh['settings'].get('length', 0))
            f = float(fps) if fps else float(sh['settings'].get('fps', 30))
            if b <= a or f <= 0:
                raise ValueError('need start < end and fps > 0')
            text, n, names = api.lanes_csv(sh, a, b, f, lanes)
            r.update(start=a, end=b, fps=f, frames=n, lanes=names)
        elif what == 'markers_json':
            text = json.dumps(api.markers_doc(sh), indent=1)
            r['markers'] = len(sh['markers'])
        elif what == 'markers_csv':
            text = api.markers_csv(sh)
            r['markers'] = len(sh['markers'])
        else:
            raise ValueError('what must be show, lanes_csv, markers_json or markers_csv')
        if file:
            if not os.path.isabs(file):
                raise ValueError('file must be absolute')
            os.makedirs(os.path.dirname(file), exist_ok=True)
            tmp = file + '.part'
            with open(tmp, 'w') as fh:
                fh.write(text)
            os.replace(tmp, file)
            r.update(file=file, bytes=len(text))
        else:
            r['text'] = text
        return r

    # ------------------------------------------------------------ recording (stepped take, handlers offline_render)
    def RecordPrepare(self, start=None, end=None, fps=None, source=None):
        """Park the transport for a take of [start, end): paused at start, In/Out = the take, Loop off, Rate 1.
        The old transport goes to storage tl_rec.saved (RecordFinish puts it back). -> plan for offline_render."""
        c = self.ownerComp
        P = c.par
        if isinstance(c.fetch('tl_rec', None), dict):
            raise RuntimeError('a take is already set up on %s (RecordFinish first)' % c.path)
        api = self._api()
        sh = self._show(api)
        ctx = api.Ctx.of(sh)
        a = api.to_seconds(start, ctx) if start is not None else float(P.Inpoint)
        b = api.to_seconds(end, ctx) if end is not None else float(P.Outpoint)
        rate = None
        try:
            rate = float(op('/').time.rate)
        except Exception:  # noqa: BLE001
            rate = float(project.cookRate)
        plan = api.record_plan(a, b, float(fps) if fps else float(P.Fps), float(P.Length), rate)
        src = c.op(source) if source else c.op('program')
        if src is None or not src.isTOP:
            raise ValueError('source %r is not a TOP in %s' % (source, c.path))
        plan['source'] = src.path
        saved = dict((n, getattr(P, n).eval()) for n in ('Play', 'Seek', 'Loop', 'Rate', 'Inpoint', 'Outpoint'))
        c.store('tl_rec', {'saved': saved, 'dt': plan['dt'], 'armed': False, 'arm_frame': -1,
                           'start': a, 'end': b, 'frames': plan['frames']})
        P.Play = False
        P.Rate = 1.0
        P.Loop = False
        P.Outpoint = b
        P.Inpoint = a
        P.Seek = a
        return plan

    def RecordArm(self):
        """Called by offline_render the moment Record goes on: play from start, one 1/cookRate step per TD frame
        (tl_actions.tick), no step in the arming frame."""
        c = self.ownerComp
        rec = c.fetch('tl_rec', None)
        if not isinstance(rec, dict):
            return False
        rec['armed'] = True
        rec['arm_frame'] = int(absTime.frame)
        c.store('tl_rec', rec)
        c.par.Play = True
        return True

    def RecordFinish(self):
        c = self.ownerComp
        rec = c.fetch('tl_rec', None)
        if not isinstance(rec, dict):
            return {}
        c.unstore('tl_rec')
        saved = rec.get('saved', {})
        for n in ('Rate', 'Loop', 'Inpoint', 'Outpoint', 'Seek', 'Play'):
            if n in saved:
                getattr(c.par, n).val = saved[n]
        return saved
'''


def build_api(comp):
    """Phase-4 ops inside an existing TL_timeline COMP (idempotent): tl_api_logic + TimelineExt Text DATs and the
    COMP's extension 0 (promoted). Extension pars are set only when present (31550 names, see the live checks)."""
    lg = _get(comp, textDAT, 'tl_api_logic')
    lg.text = open(TL_ROOT + '/timeline_api_logic.py').read()
    ex = _get(comp, textDAT, 'TimelineExt')
    ex.text = EXT_TEXT
    ex.comment = 'Agent API (phase 4): Edit/Show/State/Transport/Export/Load/Record*. MCP: td_timeline_*.'
    notes = []
    for name, val in (('ext0object', "op('./TimelineExt').module.TimelineExt(me)"), ('ext0name', 'TimelineExt'),
                      ('ext0promote', True)):
        p = getattr(comp.par, name, None)
        if p is None:
            notes.append('no par %s' % name)
            continue
        p.val = val
    try:
        comp.initializeExtensions()
    except Exception as e:  # noqa: BLE001  the handlers fall back to TimelineExt(comp) from the DAT module
        notes.append('initializeExtensions: %s' % e)
    return notes
