def _sd(o):
    """T-70: destroy only through safe_destroy (td_exec namespace, else the MCP handlers module): it closes windows
    showing the op, moves panes off, renames it out of the way and destroys it a few frames later."""
    if o is None or not o.valid:
        return None
    f = globals().get('safe_destroy') or op('/jazib_mcp/handlers').module.safe_destroy
    return f(o)


def _close_window(comp):
    """Close this COMP's own controls window before a rebuild touches anything it shows (T-70)."""
    w = comp.op('controls_window')
    if w is not None and w.OPType == 'windowCOMP' and w.isOpen:
        w.par.winclose.pulse()
        return True
    return False


def _get(comp, optype, name):
    """Reuse the op if it exists with that type (update in place); a wrong-type op goes via safe_destroy."""
    o = comp.op(name)
    if o is not None and o.OPType != optype.__name__:
        _sd(o)
        o = None
    if o is None:
        o = comp.create(optype, name)
        o.viewer = True
    return o


def _table(comp, name, rows, reset):
    d = comp.op(name)
    if d is None or reset:
        d = _get(comp, tableDAT, name)
        d.clear()
        for r in rows:
            d.appendRow(r)
    return d


def _wire(src, dst, idx=0):
    if len(dst.inputs) > idx and dst.inputs[idx] is src:
        return
    dst.inputConnectors[idx].connect(src)
    if dst.inputs[idx] is not src:
        raise RuntimeError('wire failed %s -> %s[%d]' % (src.path, dst.path, idx))


