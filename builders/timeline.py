ANNOTATE_CLONE = "op.TDAnnotate.op('annotate', includeUtility=True)"


def repair_annotates(parent_comp):
    """T-165: the widget loop in _controls used to clear `clone` on every child of `params`, the layout stage boxes
    (annotateCOMPs) too; AnnotateExt.__init__ reads par.clone.eval().par.Version, so a blank clone breaks the extension
    and every promoted attribute (Editing, TitleColor...) errors. Puts TD's default clone back and re-inits.
    -> paths repaired."""
    fixed = []
    for a in parent_comp.findChildren(type=annotateCOMP, maxDepth=1):
        if a.par.clone.eval() is None:
            a.par.clone.expr = ANNOTATE_CLONE
            a.par.clone.mode = ParMode.EXPRESSION
            a.initializeExtensions()
            fixed.append(a.path)
    return fixed


def _controls(comp, rebuild=False):
    """Controls panel, T-70 safe: the `controls` container, `ruler` and `params` are kept and updated in place; the
    autoUI widgets inside `params` are regenerated only when missing or rebuild=True (the window is closed first by
    build())."""
    ctrl = _get(comp, containerCOMP, 'controls')
    ctrl.par.w = VIEW_W
    ctrl.par.align = 'verttb'
    ruler = _get(ctrl, containerCOMP, 'ruler')
    ruler.par.w = VIEW_W
    ruler.par.h = VIEW_H
    ruler.par.top = comp.op('view_out')
    ruler.par.alignorder = 0
    params = _get(ctrl, containerCOMP, 'params')
    params.par.w = VIEW_W
    params.par.align = 'verttb'
    has_clips = comp.op('tl_clips') is not None and 'build_clip_panel' in globals()
    strip_h = globals().get('CLIP_H', 0) if has_clips else 0
    params.par.alignorder = 2 if has_clips else 1
    if has_clips:                             # phase 2: clip strip under the ruler (timeline_clips.py)
        build_clip_panel(comp, ctrl)
    for s_ in list(ctrl.children):            # strays only; ruler + cliprow + params stay
        if s_.valid and s_.name not in ('ruler', 'params') + (('cliprow',) if has_clips else ()):
            _sd(s_)
    kit = params.op('zk_rt') is not None      # zkit panel (builders/zkit.py, panel_name='controls/params'): keep it
    if not kit and (rebuild or not [w for w in params.children if w.isPanel]):
        for w_ in list(params.children):      # window closed (T-70): clear old widgets, keep the container
            _sd(w_)
        au = op('/project1/show/tools/autoUI')
        keep = {p.name: (p.mode, p.expr, p.eval()) for p in au.customPars if p.name in ('Pagetabs', 'Pagescope')}
        try:
            au.par.Pagetabs = False
            au.par.Pagescope = 'Timeline'
            au.ext.AutoUIExt.GenerateUI(customComp=comp, ui=params, shortcutDialog=False)
        finally:
            for n, (m, e, v) in keep.items():
                p = getattr(au.par, n)
                if m == ParMode.EXPRESSION:
                    p.expr = e
                else:
                    p.val = v
    repair_annotates(params)
    for w in params.children:
        if w.OPType == 'annotateCOMP':        # layout stage boxes, not widgets: keep their clone (T-165)
            continue
        if w.isPanel:
            w.par.hmode = 'fill'
        if getattr(w.par, 'clone', None) is not None:
            w.par.clone.expr = ''
            w.par.clone.mode = ParMode.CONSTANT
            w.par.clone = ''
        if getattr(w.par, 'enablecloning', None) is not None:
            w.par.enablecloning = False
    hd = params.op('header')
    if hd is not None and hasattr(hd.par, 'Headerlabel'):
        hd.par.Headerlabel = 'TIMELINE  controls'
    if kit:                                   # the kit sizes params itself; the outer panel follows it
        ctrl.par.w.expr = "max(%d, int(me.op('params').par.w))" % VIEW_W   # me.op: op() in a COMP's own par expr looks beside it
        ctrl.par.h.expr = "%d + int(me.op('params').par.h)" % (VIEW_H + strip_h)
        ctrl.par.w.mode = ParMode.EXPRESSION
        ctrl.par.h.mode = ParMode.EXPRESSION
    else:
        params.par.h = sum(int(c.par.h) for c in params.children if c.isPanel) + 6
        ctrl.par.h = VIEW_H + strip_h + int(params.par.h)
    ctrl.comment = 'CONTROLS: ruler/lanes view + sliders bound to this COMP (everything works without this panel)'
    win = _get(comp, windowCOMP, 'controls_window')
    win.par.winop = ctrl
    win.par.title = TL_NAME + ' controls'
    if not kit:
        win.par.winw = VIEW_W + 16
        win.par.winh = min(int(ctrl.par.h) + 28, 1000)
    pe = _get(comp, parameterexecuteDAT, 'controls_open')
    pe.par.op = comp
    pe.par.pars = 'Opencontrols'
    pe.par.valuechange = False
    pe.par.onpulse = True
    pe.text = OPEN
    pe.par.active = True
    ri = _get(comp, panelexecuteDAT, 'ruler_input')
    ri.par.panels = ruler
    ri.par.panelvalue = 'lselect rselect u v'
    ri.par.offtoon = True
    ri.par.ontooff = True
    ri.par.valuechange = True
    ri.par.whileon = False
    ri.par.whileoff = False
    ri.text = RULER_IN
    ri.par.active = True
    return ctrl


