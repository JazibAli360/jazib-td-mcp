def log(c, ev, detail=''):
    s = st(c)
    row = ['%.4f' % time.perf_counter(), c.par.Tc.eval(), '%.4f' % s['own'], ev, detail]
    s['ring'].maxn = max(1, int(c.par.Logmax))
